CREATE TABLE IF NOT EXISTS sites (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  name VARCHAR(64) NOT NULL,
  base_url VARCHAR(255) DEFAULT NULL,
  rss_url VARCHAR(1024) DEFAULT NULL,
  passkey VARCHAR(128) DEFAULT NULL,
  poll_interval_sec INT UNSIGNED NOT NULL DEFAULT 600,
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_sites_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS rss_items (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  site_id INT UNSIGNED NOT NULL,
  guid VARCHAR(255) NOT NULL,
  title VARCHAR(512) NOT NULL,
  download_url VARCHAR(1024) DEFAULT NULL,
  infohash CHAR(40) DEFAULT NULL,
  category VARCHAR(64) DEFAULT NULL,
  size_bytes BIGINT UNSIGNED DEFAULT NULL,
  free_type ENUM('none','free','2x','free2x') NOT NULL DEFAULT 'none',
  publish_at DATETIME DEFAULT NULL,
  raw_json JSON DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_rss_items_site_guid (site_id, guid),
  KEY idx_rss_items_infohash (infohash),
  KEY idx_rss_items_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS rules (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  name VARCHAR(128) NOT NULL,
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  priority INT NOT NULL DEFAULT 100,
  match_json JSON NOT NULL,
  action_json JSON NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_rules_name (name),
  KEY idx_rules_enabled_priority (enabled, priority)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS matched_items (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  rule_id INT UNSIGNED NOT NULL,
  rss_item_id BIGINT UNSIGNED NOT NULL,
  score INT NOT NULL DEFAULT 0,
  status ENUM('pending','downloaded','skipped','failed') NOT NULL DEFAULT 'pending',
  reason VARCHAR(255) DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_matched_rule_item (rule_id, rss_item_id),
  KEY idx_matched_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS downloads (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  hash CHAR(40) NOT NULL,
  name VARCHAR(512) DEFAULT NULL,
  rule_id INT UNSIGNED DEFAULT NULL,
  site_id INT UNSIGNED DEFAULT NULL,
  save_path VARCHAR(1024) DEFAULT NULL,
  category VARCHAR(64) DEFAULT NULL,
  tags VARCHAR(255) DEFAULT NULL,
  size_bytes BIGINT UNSIGNED DEFAULT NULL,
  state VARCHAR(32) DEFAULT NULL,
  ratio DECIMAL(10,4) DEFAULT NULL,
  uploaded BIGINT UNSIGNED DEFAULT NULL,
  downloaded BIGINT UNSIGNED DEFAULT NULL,
  progress DECIMAL(5,2) DEFAULT NULL,
  tracker VARCHAR(255) DEFAULT NULL,
  free_type ENUM('none','free','2x','free2x') NOT NULL DEFAULT 'none',
  is_protected TINYINT(1) NOT NULL DEFAULT 0,
  completed_at DATETIME DEFAULT NULL,
  last_synced_at DATETIME DEFAULT NULL,
  seeding_time INT UNSIGNED DEFAULT NULL,
  added_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_downloads_hash (hash),
  KEY idx_downloads_state (state),
  KEY idx_downloads_site (site_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS seed_policies (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  site_id INT UNSIGNED NOT NULL DEFAULT 0,          -- 0 = 全局默认，其余为站点覆盖
  target_ratio DECIMAL(6,2) NOT NULL DEFAULT 1.00,  -- 单个种子达到此分享率即视为可清理
  min_seeding_hours INT UNSIGNED NOT NULL DEFAULT 72, -- 最短做种时长（H&R 保护）
  warn_ratio DECIMAL(6,2) NOT NULL DEFAULT 1.00,    -- 站点合计分享率低于此值则告警
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_seed_policies_site (site_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS history (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  type VARCHAR(32) NOT NULL,
  message VARCHAR(512) DEFAULT NULL,
  payload_json JSON DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_history_type_created (type, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS settings (
  k VARCHAR(64) NOT NULL,
  v VARCHAR(1024) DEFAULT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (k)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
